const key = (n) => String(n).toLowerCase();

// ---------- innings generator (the Laws, as a live panel applies them) ----------
// ev: { r } runs off the bat | { wd: n } wide + n run | { nb: n } no ball + n off bat
//     { out: 'Bowled'|'Caught'|'Run Out', who?: 'striker'|'nonStriker', r?: runs completed, fielder? }
let uidSeq = 0;
function simulate(events, o){
  const bat = o.batters.slice(), bowlers = o.bowlers;
  let s = { name: bat.shift(), id: null }, n = { name: bat.shift(), id: null };
  s.id = 'id-' + key(s.name); n.id = 'id-' + key(n.name);
  let over = o.startOver || 0, done = 0, t = o.t0 || 1000;
  const balls = [];
  events.forEach(ev => {
    const legal = !(ev.wd !== undefined || ev.nb !== undefined);
    const label = { over, ballInOver: legal ? done + 1 : done };
    const bowler = bowlers[over % bowlers.length];
    let kind, runs, runsRun, dismissal = null;
    if(ev.wd !== undefined){ kind = 'Wd'; runs = 1 + ev.wd; runsRun = ev.wd; }
    else if(ev.nb !== undefined){ kind = 'Nb'; runs = 1 + ev.nb; runsRun = ev.nb; }
    else if(ev.out){ kind = 'W'; runs = ev.r || 0; runsRun = runs;
      const outName = ev.out === 'Run Out' && ev.who === 'nonStriker' ? n.name : s.name;
      dismissal = { type: ev.out, fielder: ev.fielder || null, batter: outName, batterId: 'id-' + key(outName) }; }
    else { kind = String(ev.r); runs = ev.r; runsRun = ev.r; }
    const b = {
      _id: new ObjectId(), ballUid: 'u' + (++uidSeq), matchId: 'M1', ownerUid: 'owner', innings: o.innings, battingTeam: o.team,
      over: label.over, ballInOver: label.ballInOver, kind, runs, dismissal,
      striker: s.name, strikerKey: key(s.name), strikerId: s.id, nonStriker: n.name, nonStrikerKey: key(n.name), nonStrikerId: n.id,
      bowler: bowler, bowlerKey: key(bowler), bowlerId: 'id-' + key(bowler), timestamp: (t += 10)
    };
    if(dismissal) b.dismissedPlayerKey = key(dismissal.batter);
    balls.push(b);
    if(runsRun % 2 === 1){ const x = s; s = n; n = x; }
    if(dismissal){
      const nb = bat.shift(); const nw = { name: nb, id: 'id-' + key(nb) };
      if(dismissal.batter === s.name) s = nw; else n = nw;
    }
    if(legal){ done++; if(done >= 6){ over++; done = 0; const x = s; s = n; n = x; } }
  });
  return balls;
}
// 13 overs of steady cricket for innings 1, with a wicket early on
function inningsEvents(){
  const ev = [];
  for(let ov = 0; ov < 13; ov++){
    for(let b = 1; b <= 6; b++){
      if(ov === 3 && b === 2){ ev.push({ out: 'Bowled' }); continue; }
      if(ov === 5 && b === 4){ ev.push({ wd: 0 }); }
      ev.push({ r: [0, 1, 2, 0, 4, 1, 6, 0, 3][(ov * 6 + b) % 9] });
    }
  }
  return ev;
}
